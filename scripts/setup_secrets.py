#!/usr/bin/env python3
"""Helper script to set up secrets and configuration for local development.

This script automates the complete setup process:
1. Creates the secrets directory with proper permissions
2. Moves PEM files from project root to secrets/
3. Generates base64-encoded private key for CI/CD
4. Creates .env.local with all required configuration
5. Validates the setup
"""

import base64
import contextlib
import sys
from pathlib import Path


def create_secrets_dir() -> Path:
    """Create secrets directory with secure permissions."""
    secrets_dir = Path("secrets")
    secrets_dir.mkdir(exist_ok=True)

    # Set restrictive permissions on Unix-like systems
    # Windows will ignore this gracefully
    with contextlib.suppress(Exception):
        secrets_dir.chmod(0o700)

    return secrets_dir


def convert_pem_to_base64(pem_path: Path) -> str:
    """Convert PEM file to base64-encoded raw Ed25519 seed.

    Args:
        pem_path: Path to the PEM file containing Ed25519 private key.

    Returns:
        Base64-encoded string of the raw 32-byte Ed25519 seed.
    """
    from cryptography.hazmat.backends import default_backend
    from cryptography.hazmat.primitives import serialization

    pem_data = pem_path.read_bytes()
    private_key_obj = serialization.load_pem_private_key(
        pem_data,
        password=None,
        backend=default_backend(),
    )

    # Extract raw 32-byte seed from PKCS#8 format
    raw_private = private_key_obj.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )

    return base64.b64encode(raw_private).decode("ascii")


